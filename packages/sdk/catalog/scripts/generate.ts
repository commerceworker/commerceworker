/**
 * Writes src/generated/limits.ts: the limits and patterns the catalog's routes enforce, read from
 * the modules that enforce them (`@commerceworker/core/product/paths` and `/search`, and the edge's
 * `routes.ts`), so the client rejects exactly what the edge would and never carries a hand-copied
 * constant. `--check` writes nothing and exits 1 when the committed file is stale (the drift test
 * runs it). Build tooling: nothing under src/ imports core or the delivery app.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { BATCH_MAX, CODE, LOCALE, SLUG } from '@commerceworker/core/product/paths';
import { QUERY_MAX, SEARCH_DEPTH } from '@commerceworker/core/product/search';
import {
  MAX_FILTERS,
  MAX_VALUES,
  NUMBER,
  PAGE,
  SLUG_MAX,
  SORT,
} from '../../../../apps/delivery/src/catalog/routes';

const target = fileURLToPath(new URL('../src/generated/limits.ts', import.meta.url));

const next = `/**
 * GENERATED by scripts/generate.ts from @commerceworker/core/product/paths, /search and the edge's
 * routes.ts: do not edit. Regenerate with \`pnpm sdk:generate\`; a drift test fails until you do.
 */

/** Keys, categories, SKUs, channels and attribute codes. */
export const CODE = ${CODE};
/** A locale tag: en, en-US, zh-Hant-TW. */
export const LOCALE = ${LOCALE};
/** A slug: lowercase words (any script) joined by "-". */
export const SLUG = ${SLUG};
/** The longest slug a route accepts. */
export const SLUG_MAX = ${SLUG_MAX};
/** A sort: \`newest\`, or \`<attr>_asc\` / \`<attr>_desc\`. */
export const SORT = ${SORT};
/** A bound of a numeric range, as the edge reads it. */
export const NUMBER = ${NUMBER};

/** Keys one batch lookup takes at most. */
export const BATCH_MAX = ${BATCH_MAX};
/** Products a listing or search page holds by default, and at most. */
export const PAGE = { default: ${PAGE.default}, max: ${PAGE.max} } as const;
/** Filters (term and range together) one listing request takes at most. */
export const MAX_FILTERS = ${MAX_FILTERS};
/** Values one term filter takes at most. */
export const MAX_VALUES = ${MAX_VALUES};
/** Characters of a search query the edge keeps. */
export const QUERY_MAX = ${QUERY_MAX};
/** Results a search can page through: a cursor is below this. */
export const SEARCH_DEPTH = ${SEARCH_DEPTH};
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {}
  if (current !== next) {
    console.error('src/generated/limits.ts is stale: run `pnpm sdk:generate`');
    process.exit(1);
  }
  console.log('src/generated/limits.ts is current');
} else {
  writeFileSync(target, next);
  console.log(`wrote ${target}`);
}
